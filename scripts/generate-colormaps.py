"""Regenerate vendored RGB tables without installing Matplotlib."""
import ast
from pathlib import Path
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[1]
SOURCE = "https://raw.githubusercontent.com/matplotlib/matplotlib/v3.10.0/"
GROUPS = {
    "lib/matplotlib/_cm_listed.py": ["viridis", "plasma", "inferno", "magma", "cividis", "turbo"],
    "lib/matplotlib/_cm.py": ["coolwarm", "bone", "copper", "cool", "Blues", "Greens"],
}


def interpolate(stops, t):
    for index in range(1, len(stops)):
        x, left, _ = stops[index]
        previous_x, _, previous_right = stops[index - 1]
        if t <= x:
            ratio = (t - previous_x) / (x - previous_x)
            return previous_right + (left - previous_right) * ratio
    return stops[-1][2]


tables = {}
for file, names in GROUPS.items():
    tree = ast.parse(urlopen(SOURCE + file, timeout=30).read().decode())
    for node in tree.body:
        if not isinstance(node, ast.Assign):
            continue
        for target in node.targets:
            if not isinstance(target, ast.Name) or target.id not in ["_" + name + "_data" for name in names]:
                continue
            name = target.id[1:-5].lower()
            data = ast.literal_eval(node.value)
            pixels = []
            for index in range(256):
                t = index / 255
                if isinstance(data, dict):
                    rgb = [interpolate(data[channel], t) for channel in ["red", "green", "blue"]]
                elif len(data) == 256:
                    rgb = data[index]
                else:
                    position = t * (len(data) - 1)
                    lo = min(int(position), len(data) - 2)
                    rgb = [data[lo][channel] + (data[lo + 1][channel] - data[lo][channel]) * (position - lo) for channel in range(3)]
                pixels.extend(max(0, min(255, int(value * 255 + 0.5))) for value in rgb)
            tables[name] = bytes(pixels).hex()

assert len(tables) == 12
header = "// Generated by scripts/generate-colormaps.py from Matplotlib v3.10.0.\n// Copyright (c) 2012- Matplotlib Development Team; All Rights Reserved.\n// RGB tables: 256 samples per map, encoded as hex. See third-party/matplotlib-LICENSE.txt.\n"
(ROOT / "src/colormapData.ts").write_text(header + "export const COLORMAP_HEX = {\n" + "".join(f'    {name}: "{values}",\n' for name, values in tables.items()) + "} as const;\n")
(ROOT / "third-party").mkdir(exist_ok=True)
license_text = urlopen(SOURCE + "LICENSE/LICENSE", timeout=30).read()
(ROOT / "third-party/matplotlib-LICENSE.txt").write_bytes(license_text)
(ROOT / "public/matplotlib-LICENSE.txt").write_bytes(license_text)
print(f"Generated {len(tables)} colormap tables and retained the Matplotlib license.")
